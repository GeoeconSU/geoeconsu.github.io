#!/usr/bin/env python3
"""Turn a PDF into a flip-book for the GSU homepage.

One command per publication. It renders the first pages of the PDF to WebP, writes them to
assets/books/<slug>/ and registers the book in assets/books/books.json and books.js. The homepage
reads books.js, so a new edition shows up without touching the HTML.

  python tools/build_book.py "docs/GRB Q3 2026.pdf" --slug grb-q3-2026 --group barometer \
      --title "Geoeconomic Risk Barometer" --label "Q3 2026" --order 202603 --gate "GRB Q3 2026.pdf"

Sources
  a PDF                      first --pages pages (default 11: the cover and five spreads)
  a PDF with --clip          regions of pages, in reading order: --clip PAGE:x0,y0,x1,y1 (PDF points)
  image files                one image per page, in reading order

Options
  --slug     folder name and id of the book (required)
  --group    which shelf it belongs to: "barometer", "india-horizon", ...
  --title    publication name            --label   edition name shown in the list ("Q3 2026")
  --order    sort key inside the group, highest first (use YYYYMM)
  --gate     filename the report-request form sends (must be in the worker's allow-list)
  --href     direct link to the PDF, for publications that are not gated
  --pages    how many pages to render (use an odd number so the last spread is full)
  --width    pixel width of each page image (default 1100, sharp on 2x screens)
  --remove   delete the book with this slug and exit

Needs: pip install pymupdf pillow
"""
import argparse, io, json, os, shutil, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BOOKS = os.path.join(ROOT, "assets", "books")
MANIFEST = os.path.join(BOOKS, "books.json")


def load():
    if os.path.exists(MANIFEST):
        return json.load(open(MANIFEST, encoding="utf-8"))
    return {"books": {}}


def save(m):
    os.makedirs(BOOKS, exist_ok=True)
    json.dump(m, open(MANIFEST, "w", encoding="utf-8"), indent=2, ensure_ascii=False)
    # books.js mirrors books.json so the page also works when opened straight from disk
    with open(os.path.join(BOOKS, "books.js"), "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/build_book.py. Do not edit by hand. */\n")
        f.write("window.GSU_BOOKS = " + json.dumps(m, ensure_ascii=False) + ";\n")


def to_webp(img, path, width, quality):
    from PIL import Image
    if img.mode not in ("RGB", "RGBA"):
        img = img.convert("RGB")
    if img.width != width:
        img = img.resize((width, round(img.height * width / img.width)), Image.LANCZOS)
    img.save(path, "WEBP", quality=quality, method=6)
    return img.width, img.height


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("sources", nargs="*")
    ap.add_argument("--slug", required=True)
    ap.add_argument("--group", default="library")
    ap.add_argument("--title", default="")
    ap.add_argument("--label", default="")
    ap.add_argument("--order", type=int, default=0)
    ap.add_argument("--gate", default="")
    ap.add_argument("--href", default="")
    ap.add_argument("--pages", type=int, default=11)
    ap.add_argument("--width", type=int, default=1100)
    ap.add_argument("--quality", type=int, default=82)
    ap.add_argument("--clip", action="append", default=[])
    ap.add_argument("--remove", action="store_true")
    a = ap.parse_args()

    m = load()
    out = os.path.join(BOOKS, a.slug)
    if a.remove:
        m["books"].pop(a.slug, None)
        shutil.rmtree(out, ignore_errors=True)
        save(m)
        print("removed", a.slug)
        return
    if not a.sources:
        sys.exit("Give a PDF or a list of page images.")

    from PIL import Image
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(out)
    pages, sizes = [], []

    def add(img):
        n = len(pages) + 1
        name = f"p{n:02d}.webp"
        img = img.convert("RGB")
        if sizes:
            # every page takes the shape of the first: a page of another shape is centred on paper of its own colour
            w0, h0 = sizes[0]
            want = h0 / w0
            if abs(img.height / img.width - want) > 0.01:
                cw = max(img.width, round(img.height / want)); ch = round(cw * want)
                paper = img.getpixel((img.width // 2, max(2, img.height // 40)))
                canvas = Image.new("RGB", (cw, ch), paper)
                canvas.paste(img, ((cw - img.width) // 2, (ch - img.height) // 2))
                img = canvas
        sizes.append(to_webp(img, os.path.join(out, name), a.width, a.quality))
        pages.append(f"assets/books/{a.slug}/{name}")

    first = a.sources[0]
    if first.lower().endswith(".pdf"):
        import pymupdf
        doc = pymupdf.open(first)
        if a.clip:
            for c in a.clip:
                pno, box = c.split(":")
                x0, y0, x1, y1 = (float(v) for v in box.split(","))
                rect = pymupdf.Rect(x0, y0, x1, y1)
                z = a.width * 1.25 / rect.width
                pix = doc[int(pno) - 1].get_pixmap(matrix=pymupdf.Matrix(z, z), clip=rect, alpha=False)
                add(Image.open(io.BytesIO(pix.tobytes("png"))))
        else:
            for i in range(min(a.pages, doc.page_count)):
                pg = doc[i]
                z = a.width * 1.25 / pg.rect.width          # render above target, then downsample: crisper text
                pix = pg.get_pixmap(matrix=pymupdf.Matrix(z, z), alpha=False)
                add(Image.open(io.BytesIO(pix.tobytes("png"))))
    else:
        for src in a.sources:
            add(Image.open(src))

    w, h = sizes[0]
    m["books"][a.slug] = {
        "slug": a.slug, "group": a.group, "title": a.title, "label": a.label, "order": a.order,
        "ratio": round(w / h, 4), "pages": pages,
        **({"gate": a.gate} if a.gate else {}), **({"href": a.href} if a.href else {}),
    }
    save(m)
    kb = sum(os.path.getsize(os.path.join(ROOT, p)) for p in pages) // 1024
    print(f"{a.slug}: {len(pages)} pages, {w}x{h}, {kb} KB -> assets/books/{a.slug}/")
    if len(pages) % 2 == 0:
        print("note: an odd page count ends on a full spread; this book has", len(pages))


if __name__ == "__main__":
    main()
